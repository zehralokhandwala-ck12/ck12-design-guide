const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const vm = require('node:vm');
const {execFileSync} = require('node:child_process');
const assert = require('node:assert/strict');
const model = require('../contribute/model.js');

const registryPath = 'contribute/published.js';
const registryPrefix = 'const REVIEWED_CHANGES = ';
const repo = process.env.GITHUB_REPOSITORY || model.repository;
const api = 'https://api.github.com/repos/' + repo;
const git = (...args) => execFileSync('git', args, {encoding:'utf8'}).trim();
const digest = data => crypto.createHash('sha256').update(data).digest('hex');

function loadState() {
  const data = vm.runInNewContext(fs.readFileSync('specs.js','utf8') + '\nDATA');
  const file = fs.readFileSync(registryPath,'utf8').trim();
  assert.ok(file.startsWith(registryPrefix) && file.endsWith(';'), 'Invalid reviewed registry');
  const records = JSON.parse(file.slice(registryPrefix.length,-1));
  records.forEach(r => model.apply(data,r));
  const figures = JSON.parse(fs.readFileSync('source-images/catalog.json','utf8')).flatMap(d=>d.figures);
  return {data, records, figures};
}
function summary(text) {
  if (process.env.GITHUB_STEP_SUMMARY) fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY,text + '\n');
  console.log(text);
}
async function request(endpoint, method='GET', body) {
  const response = await fetch(api+endpoint, {method,headers:{Accept:'application/vnd.github+json',
    Authorization:'Bearer '+process.env.GH_TOKEN,'X-GitHub-Api-Version':'2022-11-28'},body:body ? JSON.stringify(body) : undefined});
  const result = await response.json();
  if(!response.ok) throw Object.assign(new Error('GitHub '+response.status+': '+result.message),{status:response.status});
  return result;
}
function readIssue(issue) {
  assert.ok(!issue.pull_request && issue.state==='open' && issue.title.startsWith('[Spec proposal]'), 'Select an open spec proposal issue.');
  const match = issue.body?.match(/^## Proposal data\s*\n\x60\x60\x60json\s*\n([\s\S]*?)\n\x60\x60\x60\s*$/m);
  assert.ok(match && match[1].length<=32000,'The issue needs the JSON proposal generated by the guide.');
  const imageBlock = issue.body.match(/^## Reference image\s*\n([\s\S]*?)^## Proposal data/m)?.[1] || '';
  const attachments = [...new Set(imageBlock.match(/https:\/\/github\.com\/user-attachments\/assets\/[a-f0-9-]{36}\b/gi) || [])];
  assert.ok(attachments.length<=1,'Attach one reference image per proposal.');
  if (/!\[|<img\b|uploading/i.test(imageBlock)) assert.ok(attachments.length,'Finish uploading the PNG or JPEG to the Reference image section.');
  return {input:JSON.parse(match[1]),attachment:attachments[0]};
}
async function downloadImage(url) {
  // Fetch only a public GitHub attachment. No credentials are sent to media hosts.
  let next = new URL(url);
  for(let i=0;i<5;i++) {
    assert.ok(next.protocol==='https:' && !next.username && !next.password && !next.port &&
      (next.hostname==='github.com' || next.hostname.endsWith('.githubusercontent.com')), 'Unexpected attachment host.');
    const r=await fetch(next,{redirect:'manual',signal:AbortSignal.timeout(30000)});
    if(r.status>=300 && r.status<400 && r.headers.has('location')){next=new URL(r.headers.get('location'),next);continue;}
    assert.ok(r.ok && r.body,'The reference image could not be downloaded. Attach a public PNG or JPEG.');
    let total=0;const chunks=[];
    for await(const chunk of r.body){total+=chunk.length;assert.ok(total<=10*1024*1024,'Use a reference image under 10 MB.');chunks.push(chunk);}
    const bytes=Buffer.concat(chunks);
    const png=bytes.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10]));
    const jpeg=bytes[0]===255 && bytes[1]===216 && bytes[2]===255;
    assert.ok(png || jpeg,'The attachment must be a PNG or JPEG.');
    return {bytes,ext:png?'png':'jpg'};
  }
  throw Error('Too many attachment redirects.');
}
function writeCandidate(records, record, image) {
  const changed = [registryPath];
  if(image){
    const asset = 'contribute/images/issue-'+record.issue+'-'+digest(image.bytes).slice(0,12)+'.'+image.ext;
    fs.mkdirSync(path.dirname(asset),{recursive:true});fs.writeFileSync(asset,image.bytes);changed.push(asset);
    record.attachment={src:asset,caption:record.attachmentCaption || 'Reference from proposal '+record.issue};
  }
  delete record.attachmentCaption;
  const registry=registryPrefix+JSON.stringify([...records,record],null,2)+';\n';
  fs.writeFileSync(registryPath,registry);
  for(const page of ['index.html','math-review/index.html','contribute/index.html']){
    const original=fs.readFileSync(page,'utf8');
    const updated=original.replace(/published\.js\?v=[0-9a-f]+/, 'published.js?v='+digest(registry).slice(0,12));
    assert.notEqual(original,updated,'Missing registry version in '+page);
    fs.writeFileSync(page,updated);changed.push(page);
  }
  return changed;
}
function pilot() {
  const {data,figures}=loadState();
  const graph={version:1,kind:'spec',subject:'math',category:'graphs',title:'Pilot graph '+crypto.randomUUID(),
    scope:'Grades 6–8',source:'Workflow verification fixture',properties:[{label:'Stroke',value:'2 px'}],
    related:['graph-grid'],figureId:'math-2025-p261'};
  const spec=model.validate(graph,data,figures);
  model.apply(data,spec);assert.ok(model.entries(data).some(e=>e.id===spec.id));
  assert.throws(()=>model.validate(graph,data,figures),/already exists/);
  const palette=model.entries(data).find(e=>e.id==='pie-colors');
  const before=model.colors(palette);
  let next=0;while(before.includes('#'+next.toString(16).padStart(6,'0').toUpperCase()))next++;
  const proposal={version:1,kind:'color',subject:'math',category:'graphs',target:palette.id,operation:'add',position:1,
    color:'#'+next.toString(16).padStart(6,'0'),before,scope:'Pilot only',role:'Review fixture',source:'Workflow verification fixture'};
  const color=model.validate(proposal,data,figures);model.apply(data,color);
  assert.deepEqual(Array.from(model.colors(palette)),Array.from(model.afterColors(color)));
  assert.throws(()=>model.validate(proposal,data,figures),/has changed/);
  summary('Both in-memory pilot proposals passed: new graph, shared rule, figure, palette insertion, duplicate and stale-order checks. No changes were written.');
}
async function prepare() {
  if(process.env.PROPOSAL_MODE==='pilot')return pilot();
  const rawNumber=process.env.PROPOSAL_ISSUE || '';
  assert.match(rawNumber,/^[1-9]\d{0,9}$/,'Enter the proposal issue number.');
  const number=Number(rawNumber);
  const issue=await request('/issues/'+number);
  const {input,attachment}=readIssue(issue);
  const {data,records,figures}=loadState();
  assert.ok(!records.some(r=>r.issue===number),'This issue is already published.');
  const record=model.validate(input,data,figures);record.issue=number;
  const image=attachment ? await downloadImage(attachment) : null;
  if(image && typeof input.caption==='string')record.attachmentCaption=input.caption.trim().slice(0,300);
  const base=git('rev-parse','HEAD');
  const branch='spec-review-'+number+'-'+digest(JSON.stringify([base,record,image && digest(image.bytes)])).slice(0,12);
  const changes=writeCandidate(records,record,image);
  loadState(); // Replay the complete updated registry before creating a review branch.
  if(!git('ls-remote','--heads','origin',branch)){
    git('switch','-c',branch);git('add','--',...changes);
    git('-c','user.name=CK-12 spec review','-c','user.email=41898282+github-actions[bot]@users.noreply.github.com',
      'commit','-m','Prepare guide change from issue #'+number);
    git('push','origin','HEAD:refs/heads/'+branch);
  }
  const compare='https://github.com/'+repo+'/compare/main...'+branch+'?expand=1';
  summary('Prepared review branch for issue #'+number+'. [Review changes and open a pull request]('+compare+'). Merge the approved change to publish it.');
  const open=await request('/pulls?state=open&head='+encodeURIComponent(repo.split('/')[0]+':'+branch));
  if(open.length){summary('[Existing pull request]('+open[0].html_url+')');return;}
  const title=record.kind==='spec'?'Add '+record.title:'Update '+record.target+' palette';
  try {
    const pr=await request('/pulls','POST',{title,head:branch,base:'main',draft:true,
      body:'Proposed from #'+number+'. Review the values, scope and source in the linked proposal and the versioned guide change. Merging publishes the change.\n\nCloses #'+number});
    summary('[Open draft pull request]('+pr.html_url+')');
  } catch(err) {
    if(err.status!==403)throw err;
    summary('The repository restricts pull requests created by Actions. Use the compare link above to open the pull request with your GitHub account.');
  }
}
if(require.main===module)prepare().catch(err=>{console.error(err.message);process.exitCode=1});
module.exports={loadState,readIssue,writeCandidate,pilot};
